def listar_chamados_abertos_db():
    """Retorna os chamados com status 'Aberto' ou 'Em Andamento'."""
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
        SELECT c.id, cl.nome, c.categoria, c.aplicacao, c.prioridade, c.status
        FROM chamados c
        JOIN clientes cl ON c.cliente_id = cl.id
        WHERE c.status != 'Encerrado'
        ORDER BY c.id DESC
    """)
    dados = cursor.fetchall()
    cursor.close()
    conn.close()
    return dados


def adicionar_anotacao_db(chamado_id, anotacao):
    """Registra uma anotação no histórico e altera status para 'Em Andamento' se estivesse 'Aberto'."""
    conn = get_connection()
    cursor = conn.cursor()
    
    cursor.execute("INSERT INTO historico_chamados (chamado_id, anotacao) VALUES (:1, :2)", (chamado_id, anotacao))
    cursor.execute("UPDATE chamados SET status = 'Em Andamento' WHERE id = :1 AND status = 'Aberto'", (chamado_id,))
    
    conn.commit()
    cursor.close()
    conn.close()


def encerrar_chamado_db(chamado_id, solucao):
    """Encerra o chamado e salva a data de fechamento e solução final."""
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
        UPDATE chamados 
        SET status = 'Encerrado', 
            solucao = :1, 
            data_fechamento = CURRENT_TIMESTAMP 
        WHERE id = :2
    """, (solucao, chamado_id))
    
    # Registra o encerramento no histórico também
    cursor.execute("INSERT INTO historico_chamados (chamado_id, anotacao) VALUES (:1, :2)", 
                   (chamado_id, f"[CHAMADO ENCERRADO] Solução: {solucao}"))
    
    conn.commit()
    cursor.close()
    conn.close()


def obter_historico_chamado_db(chamado_id):
    """Retorna todo o histórico de anotações de um chamado especifico."""
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
        SELECT TO_CHAR(data_registro, 'DD/MM/YYYY HH24:MI'), anotacao 
        FROM historico_chamados 
        WHERE chamado_id = :1 
        ORDER BY id ASC
    """, (chamado_id,))
    dados = [
        (data_registro, _ler_clob(anotacao))
        for data_registro, anotacao in cursor.fetchall()
    ]
    cursor.close()
    conn.close()
    return dados

def _ler_clob(valor):
    """Converte valores CLOB do Oracle para texto comum."""
    if valor is None:
        return ""
    return valor.read() if hasattr(valor, "read") else str(valor)

def listar_chamados_encerrados_db(
    data_inicio=None,
    data_fim=None,
    cliente_id=None,
    funcionario_id=None
):
    """
    Retorna chamados encerrados com filtros opcionais.
    As datas devem ser informadas no formato YYYY-MM-DD.
    """
    conn = get_connection()
    cursor = conn.cursor()

    sql = """
        SELECT
            c.id,
            cl.nome,
            NVL(f.nome, 'Não atribuído'),
            c.categoria,
            c.aplicacao,
            c.prioridade,
            TO_CHAR(c.data_fechamento, 'DD/MM/YYYY HH24:MI')
        FROM chamados c
        INNER JOIN clientes cl ON cl.id = c.cliente_id
        LEFT JOIN funcionarios f ON f.id = c.funcionario_id
        WHERE c.status = 'Encerrado'
          AND (
                :data_inicio IS NULL
                OR c.data_fechamento >= TO_TIMESTAMP(:data_inicio, 'YYYY-MM-DD')
              )
          AND (
                :data_fim IS NULL
                OR c.data_fechamento < TO_TIMESTAMP(:data_fim, 'YYYY-MM-DD')
                    + INTERVAL '1' DAY
              )
          AND (
                :cliente_id IS NULL
                OR c.cliente_id = :cliente_id
              )
          AND (
                :funcionario_id IS NULL
                OR c.funcionario_id = :funcionario_id
              )
        ORDER BY c.data_fechamento DESC
    """

    parametros = {
        "data_inicio": data_inicio,
        "data_fim": data_fim,
        "cliente_id": cliente_id,
        "funcionario_id": funcionario_id
    }

    cursor.execute(sql, parametros)
    dados = cursor.fetchall()

    cursor.close()
    conn.close()

    return dados

def obter_chamado_encerrado_detalhe_db(chamado_id):
    """Retorna todos os dados necessários para a tela de detalhe de um chamado."""
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("""
        SELECT 
            c.id,
            cl.nome AS Cliente,
            NVL(f.nome, 'Nao atribuido') AS tecnico,
            c.categoria,
            c.aplicacao,
            c.prioridade,
            TO_CHAR(c.data_criacao, 'DD/MM/YYYY HH24:MI') AS data_criacao,
            TO_CHAR(c.data_fechamento, 'DD/MM/YYYY HH24:MI') AS data_fechamento,
            c.descricao,
            c.solucao
        FROM chamados c
        JOIN clientes cl ON cl.id = c.cliente_id
        LEFT JOIN funcionarios f ON f.id = c.funcionario_id
        WHERE c.id = :chamado_id 
            AND c.status = 'Encerrado'
    """, {"chamado_id": chamado_id})

    chamado = cursor.fetchone()

    cursor.close()
    conn.close()

    if not chamado:
        return None

    chamado = list(chamado)
    chamado[6] = _ler_clob(chamado[6])  # descricao
    chamado[7] = _ler_clob(chamado[7])  # solucao

    return chamado