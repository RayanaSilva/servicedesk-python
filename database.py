import os
import oracledb
from dotenv import load_dotenv

load_dotenv()

# Configurações de Conexão com o Oracle
ORACLE_USER = os.getenv("ORACLE_USER")
ORACLE_PASSWORD = os.getenv("ORACLE_PASSWORD")
ORACLE_DSN = os.getenv("ORACLE_DSN", "localhost:1521/FREEPDB1")


def get_connection():
    return oracledb.connect(
        user=ORACLE_USER, password=ORACLE_PASSWORD, dsn=ORACLE_DSN
    )


def init_db():
    conn = get_connection()
    cursor = conn.cursor()

    def executar_ddl(sql):
        try:
            cursor.execute(sql)
        except oracledb.DatabaseError as e:
            error_obj, = e.args
            # ORA-00955 (objeto existe) ou ORA-01430 (coluna existe)
            if error_obj.code not in (955, 1430):
                raise e

    # 1. Tabela Clientes
    executar_ddl("""
        CREATE TABLE clientes (
            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome VARCHAR2(100) NOT NULL,
            email VARCHAR2(100),
            telefone VARCHAR2(20)
        )
    """)

    # 2. Tabela Funcionários
    executar_ddl("""
        CREATE TABLE funcionarios (
            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome VARCHAR2(100) NOT NULL,
            equipe VARCHAR2(50),
            cargo VARCHAR2(50),
            email VARCHAR2(100)
        )
    """)

    # 3. Tabela Chamados
    executar_ddl("""
        CREATE TABLE chamados (
            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            cliente_id NUMBER,
            funcionario_id NUMBER,
            categoria VARCHAR2(50) NOT NULL,
            aplicacao VARCHAR2(100) NOT NULL,
            prioridade VARCHAR2(20) DEFAULT 'Média',
            descricao CLOB,
            solucao CLOB,
            status VARCHAR2(20) DEFAULT 'Aberto',
            data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            data_fechamento TIMESTAMP,
            sla_horas NUMBER DEFAULT 24,
            CONSTRAINT fk_chamado_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(id),
            CONSTRAINT fk_chamado_funcionario FOREIGN KEY (funcionario_id) REFERENCES funcionarios(id)
        )
    """)

    # Tenta adicionar a coluna 'solucao' caso a tabela 'chamados' já existisse no seu Oracle
    executar_ddl("ALTER TABLE chamados ADD solucao CLOB")

    # 4. Tabela Historico/Anotações dos Chamados (Essencial para análise temporal)
    executar_ddl("""
        CREATE TABLE historico_chamados (
            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            chamado_id NUMBER NOT NULL,
            anotacao CLOB NOT NULL,
            data_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT fk_hist_chamado FOREIGN KEY (chamado_id) REFERENCES chamados(id)
        )
    """)

    conn.commit()
    cursor.close()
    conn.close()


